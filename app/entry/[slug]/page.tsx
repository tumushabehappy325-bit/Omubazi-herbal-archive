import Link from "next/link";
import { notFound } from "next/navigation";
import AttributionBadge from "@/components/AttributionBadge";
import EntrySafetyPanel from "@/components/EntrySafetyPanel";
import entries from "@/data/entries.json";
import { getEntryBySlug } from "@/lib/match-entries";
import type { HerbalEntry } from "@/lib/types";

const herbalEntries = entries as HerbalEntry[];

interface EntryPageProps {
  params: { slug: string };
}

export function generateStaticParams() {
  return herbalEntries.map((entry) => ({ slug: entry.slug }));
}

export function generateMetadata({ params }: EntryPageProps) {
  const entry = getEntryBySlug(herbalEntries, params.slug);
  if (!entry) return { title: "Entry not found — Omubazi" };
  return {
    title: `${entry.plantName} — Omubazi`,
    description: `Traditional use: ${entry.ailment}`,
  };
}

export default function EntryPage({ params }: EntryPageProps) {
  const entry = getEntryBySlug(herbalEntries, params.slug);
  if (!entry) notFound();

  return (
    <div className="mx-auto max-w-3xl px-5 pb-16 pt-8 sm:px-8 sm:pt-12">
      <Link
        href="/"
        className="font-body text-sm text-forest-mist underline decoration-forest/25 underline-offset-4 transition hover:text-clay hover:decoration-clay"
      >
        ← Back to catalog
      </Link>

      <article className="mt-8 animate-fade-up">
        <header className="specimen-border bg-parchment/90 px-5 py-7 sm:px-8 sm:py-9">
          <p className="font-body text-[10px] uppercase tracking-[0.2em] text-clay">
            Archive specimen
          </p>
          <h1 className="mt-3 font-display text-3xl leading-snug text-forest-deep sm:text-4xl">
            <em>{entry.plantName}</em>
          </h1>
          <p className="mt-2 font-body text-lg text-forest-mist">
            {entry.localName}
          </p>
          <div className="mt-6">
            <AttributionBadge
              sourceAttribution={entry.sourceAttribution}
              region={entry.region}
            />
          </div>
        </header>

        <section
          className="mt-8 border border-forest/15 bg-parchment-dark/25 px-5 py-6 sm:px-7"
          aria-labelledby="tradition-heading"
        >
          <h2
            id="tradition-heading"
            className="font-display text-xl text-forest-deep"
          >
            Traditional knowledge
          </h2>
          <p className="mt-1 font-body text-xs uppercase tracking-[0.12em] text-moss">
            From the archive — not generated by AI
          </p>

          <dl className="mt-6 space-y-5">
            <div>
              <dt className="font-body text-xs uppercase tracking-[0.14em] text-clay">
                Traditionally used for
              </dt>
              <dd className="mt-1.5 font-body text-base leading-relaxed text-parchment-ink/90">
                {entry.ailment}
              </dd>
            </div>
            <div className="field-rule" />
            <div>
              <dt className="font-body text-xs uppercase tracking-[0.14em] text-clay">
                General preparation
              </dt>
              <dd className="mt-1.5 font-body text-base leading-relaxed text-parchment-ink/90">
                {entry.preparation}
              </dd>
            </div>
          </dl>

          {entry.disclosureTier === "gated" ? (
            <p className="mt-6 border border-clay/30 bg-clay-soft/40 px-4 py-3 font-body text-sm leading-relaxed text-forest-deep">
              <span className="font-semibold text-clay">Gated detail. </span>
              Precise preparation and dosing for this plant require consulting
              the named healer or community steward, or a qualified health
              worker. Only general information is shown here.
            </p>
          ) : null}
        </section>

        <div className="mt-8">
          <EntrySafetyPanel slug={entry.slug} plantName={entry.plantName} />
        </div>
      </article>
    </div>
  );
}
